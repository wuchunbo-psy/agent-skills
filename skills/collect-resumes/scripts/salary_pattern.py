# -*- coding: utf-8 -*-
"""
salary_pattern.py — 薪酬正则单一真相源。

verify_archive.py（扫薪酬）和 redact_salary.py（删薪酬）共用此正则，
杜绝手工复制导致的漂移（改一处忘另一处 → 扫到的删不掉或已删的仍误报）。
修改正则必须同步跑 tests/python 的薪酬用例（防误报年份/日期、防漏报裸金额）。
"""

import re

SALARY = re.compile(
    # ── K/万 区间 + 4位数字区间（"期望薪资 25-30K" "期望薪资：35000~40000元/月" "月薪30000-35000"）──
    # ⚠️ 区间分支必须放在"词+裸数字"和"纯标签"之前：alternation 有序、首个命中胜，
    #    短分支先命中会消费掉薪词，区间只剩残段且闸门同正则同样漏报
    #    （2026-09-03 舒笛案：「期望薪资：35000~40000元/月」被截成「期望薪资：35000」，
    #    残留「~40000元/月」双向失灵）。
    #    4位分支第二段 \d{4,} 天然排除日期（"期望入职2026-08-15"第二段仅2位不命中）。
    r"(期望薪资|薪资|月薪|年薪)\s*\d[\d,.\s]*[-—~至]+\d[\d,.\s]*\s*[Kk万]"
    r"|(薪|月薪|年薪|税前|税后|到手|期望).{0,6}\d{4,}\s*[-—~至]\s*\d{4,}"
    # ── 薪资词 + K/万单值（"月薪：15K" "到手2万"）──
    # 同样必须在纯标签分支之前，否则「月薪」标签被消费后残留「：15K」。
    r"|(薪|薪水|薪资|月薪|年薪|税前|税后|到手).{0,6}\d{1,2}\s*[Kk万wW]"
    # ── 薪资词 + 裸 4+ 位金额（"月薪30000""底薪18000"）──
    # (?![年]|[-/]\d) 排除日期误报："期望到岗时间2026年8月" / "期望入职2026-08-15"。
    # 数字区间已被上方分支整体兜住，本分支只兜单值，不会把区间截断。
    r"|(月薪|年薪|薪资|薪水|底薪|税前|税后|到手|期望).{0,4}\d{4,}(?![年]|[-/]\d)"
    # ── 纯薪资词标签（"期望薪资：" "薪资面议"，无数字也要命中供人工复核）──
    r"|(期望薪资|期望薪水|当前薪资|目前薪资|薪资[：:]|薪水[：:]?|月薪|年薪|"
    r"待遇[：:]|薪金|税前|税后|到手|底薪|薪资面议|面议)"
    # ── base：独立词（前后非字母），排除 codebase/database/baseline 技术合成词 ──
    r"|(?<![a-zA-Z])[Bb]ase(?![a-zA-Z])"
    # ── 短数字K区间（"15-25K"，无薪词前缀）──
    r"|\d{1,2}\s*[Kk]?\s*[-—~至]\s*\d{1,2}\s*[Kk](?!PT|HZ|分辨率|帧|视频|贴图)"
    # ── 裸万/W 区间（"25万-30万" "20W-30W"，数字限 1-2 位排除 4 位年份）──
    r"|\d{1,2}\s*[万wW]\s*[-—~至]\s*\d{1,2}\s*[万wW]"
    # ── 英文单值（"Salary: 30K"；re 无 IGNORECASE，手写大小写变体）──
    r"|([Ss]alary|[Pp]ay|[Cc]ompensation|[Cc][Tt][Cc])\s*[:：]?\s*\d{1,2}\s*[Kk](?!PT|HZ|分辨率|帧|视频|贴图)"
)
